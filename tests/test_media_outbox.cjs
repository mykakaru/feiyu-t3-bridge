const assert=require('node:assert/strict'),fs=require('node:fs'),os=require('node:os'),path=require('node:path');
const {sendOnce,hash,contentHash}=require('../bridge/outbox.cjs');
const {stage,receive,readRecord}=require('../bridge/inbox.cjs');
const {EXACT_MEDIA_HOST}=require('../bridge/scoped_media.cjs');
(async()=>{
 const root=fs.mkdtempSync(path.join(os.tmpdir(),'wecom-media-test-'));
 fs.mkdirSync(path.join(root,'outgoing-media'));
 fs.writeFileSync(path.join(root,'outgoing-media','sample.bin'),Buffer.from('media-fixture'));
 const session={verified_by_root:true,evidence_ref:'fixture',chatid:'g',task_id:'t',last_user_interaction_at:new Date().toISOString()};
 const media={type:'video',relative_path:'outgoing-media/sample.bin',filename:'sample.mp4',bytes:13,sha256:hash('media-fixture')};
 const job={job_id:'media-one',chatid:'g',task_id:'t',media,approval:{root_reviewed:true,owner_authorization_ref:'fixture-owner',audience:'g'}};
 job.approval.content_sha256=contentHash(job);
 let uploads=0,sends=0;
 const client={uploadMedia:async(buffer,options)=>{uploads++;assert.equal(buffer.toString(),'media-fixture');assert.equal(options.type,'video');return {type:'video',media_id:'fixture-media'};},sendMediaMessage:async(chat,type,id)=>{sends++;assert.equal(chat,'g');assert.equal(type,'video');assert.equal(id,'fixture-media');return {errcode:0};}};
 assert.equal((await sendOnce(root,job,session,client)).state,'server_accepted');
 await sendOnce(root,job,session,client);assert.equal(uploads,1);assert.equal(sends,1);
 fs.writeFileSync(path.join(root,'outgoing-media','sample.bin'),'altered');
 assert.equal((await sendOnce(root,{...job,job_id:'changed'},session,client)).reason,'invalid_or_changed_media');
 const escaping={...job,job_id:'escape',media:{...media,relative_path:'../private.bin'}};
 escaping.approval={...job.approval,content_sha256:contentHash(escaping)};
 assert.equal((await sendOnce(root,escaping,session,client)).state,'not_sent');
 assert.equal(sends,1);
 const fixtureKey=Buffer.alloc(32,32).toString('base64');
 const frame={msgid:'staged',chattype:'single',from:{userid:'fixture'},msgtype:'image',image:{url:'https://'+EXACT_MEDIA_HOST+'/fixture',aeskey:fixtureKey}};
 const staged=stage(root,frame);
 const original=fs.readFileSync(path.join(root,'queue',hash('staged')+'.json'));
 const pending=JSON.parse(original);
 assert.equal(pending.delivery,'pending');assert.equal(pending.media_status,'processing');assert.equal(pending.attachment_count,1);assert.equal(original.includes(fixtureKey),false);
 await receive(root,frame,async()=>({buffer:Buffer.from('image')}),staged);
 assert.deepEqual(fs.readFileSync(path.join(root,'queue',hash('staged')+'.json')),original);
 const complete=readRecord(root,'staged');assert.equal(complete.media_status,'completed');assert.equal(complete.attachments[0].state,'downloaded');
 console.log('PASS media digest/audience, same-connection upload/send, dedup, changed-file/traversal rejection, synchronous metadata durability. Offline fixtures only.');
})();
